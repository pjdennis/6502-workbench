def length(op):
    """Bytes in the instruction that starts with this opcode."""
    return OP_LEN[op]


def zp_opcode(op, cpu):
    """The zero page opcode for an absolute one, and whether there is one."""
    z = ZP_FORM[op]
    if z != 0:
        return z, True
    if cpu == CPU_65C02:
        # The absolute instructions the 65C02 adds: TSB, TRB, BIT abs,X, STZ and STZ abs,X.
        if op == 0x0C or op == 0x1C or op == 0x3C:
            return op - 8, True
        if op == 0x9C:
            return 0x64, True
        if op == 0x9E:
            return 0x74, True
    return 0, False


def is_branch(op, cpu):
    """True if the last byte of the instruction is a displacement relative to the next one."""
    if (op & 0x1F) == 0x10:
        return True
    if cpu == CPU_65C02:
        # BRA, and BBR/BBS whose third byte is the displacement.
        return op == 0x80 or (op & 0x0F) == 0x0F
    return False

#!/usr/bin/env python3
"""Assemble the bbcbplus MOS ROM (bbc_mos_rom.asm) into a C header.

Usage: emulator/bbc_mos_to_c.py emulator/bbc_mos_rom.asm -o emulator/bbc_mos_rom_generated.h

The source is in the dialect of the repository's own assembler (asm/17)
and is assembled with its Python work-alike, asm/pyasm.py. The header
holds the 16 KB image ($C000-$FFFF) as bbc_mos_rom[], a BBC_MOS_<LABEL>
define for each global label, and bbc_mos_traps[], the host trap sites
(labels t_<name>). Each trap must be the byte $02 right after a NOP.
"""

import argparse
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "asm"))
import pyasm  # noqa: E402

BASE = 0xC000
SIZE = 0x4000
TRAP = 0x02
NOP = 0xEA


def assemble(src):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "mos.bin")
        asm = pyasm.Assembler(src, out)
        asm.run()
        with open(out, "rb") as f:
            image = f.read()
    labels = {key[1]: value for key, value in asm.symbols.items() if key[0] == "global"}
    return image, labels


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("source")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    image, labels = assemble(args.source)
    if len(image) != SIZE or labels.get("mos_title") != BASE:
        sys.exit(f"bbc_mos_to_c: the image must fill ${BASE:04X}-$FFFF ({len(image)} bytes)")
    traps = sorted((v, k) for k, v in labels.items() if k.startswith("t_"))
    for addr, name in traps:
        if image[addr - BASE] != TRAP or image[addr - BASE - 1] != NOP:
            sys.exit(f"bbc_mos_to_c: trap {name} at ${addr:04X} is not $02 after a NOP")

    src_name = os.path.relpath(os.path.abspath(args.source), os.path.join(HERE, ".."))
    lines = [
        f"/* Generated by emulator/bbc_mos_to_c.py from {src_name}; do not edit. */",
        "#ifndef EMULATOR_BBC_MOS_ROM_GENERATED_H",
        "#define EMULATOR_BBC_MOS_ROM_GENERATED_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    for name in sorted(labels):
        lines.append(f"#define BBC_MOS_{name.upper()} 0x{labels[name]:04X}")
    lines += ["", f"#define BBC_MOS_TRAP_COUNT {len(traps)}",
              "static const uint16_t bbc_mos_traps[BBC_MOS_TRAP_COUNT] = {"]
    lines += [f"    0x{addr:04X},  /* {name} */" for addr, name in traps]
    lines += ["};", "", f"static const uint8_t bbc_mos_rom[0x{SIZE:04X}] = {{"]
    for i in range(0, SIZE, 16):
        row = ", ".join(f"0x{b:02X}" for b in image[i:i + 16])
        lines.append(f"    {row},")
    lines += ["};", "", "#endif", ""]
    with open(args.output, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
